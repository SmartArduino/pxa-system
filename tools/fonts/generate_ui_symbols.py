#!/usr/bin/env python3
"""Extract the existing LVGL Font Awesome symbols into read-only DPI banks.

No font converter or network is needed. Input is LVGL's uncompressed 4-bit
Montserrat+FontAwesome generated C; Latin glyphs and kerning are omitted.
Font data: Font Awesome Free, SIL OFL 1.1; see symbols-LICENSE.txt.
"""
import argparse
from pathlib import Path
import re

SIZES = (8, 12, 16, 24, 32, 48)


def array(source, name):
    match = re.search(r'\b' + re.escape(name) + r'\[\]\s*=\s*\{(.*?)\n\};', source, re.S)
    if not match:
        raise ValueError(f'Missing array: {name}')
    return match[1]


def numbers(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return [int(x, 0) for x in re.findall(r'0x[0-9a-fA-F]+|\b\d+\b', text)]


def extract(path, size):
    source = path.read_text()
    if not re.search(r'\.bpp\s*=\s*4\b', source) or not re.search(r'\.bitmap_format\s*=\s*0\b', source):
        raise ValueError('Only uncompressed 4-bit input is supported')
    bitmap = bytes(numbers(array(source, 'glyph_bitmap')))
    glyphs = []
    for block in re.findall(r'\{([^{}]+)\}', array(source, 'glyph_dsc')):
        glyphs.append({k: int(v) for k, v in re.findall(r'\.(\w+)\s*=\s*(-?\d+)', block)})
    entries = []
    for block in re.findall(r'\{([^{}]+)\}', array(source, 'cmaps')):
        if 'LV_FONT_FMT_TXT_CMAP_SPARSE_TINY' not in block:
            continue
        start = int(re.search(r'\.range_start\s*=\s*(\d+)', block)[1])
        glyph = int(re.search(r'\.glyph_id_start\s*=\s*(\d+)', block)[1])
        name = re.search(r'\.unicode_list\s*=\s*(\w+)', block)[1]
        for i, offset in enumerate(numbers(array(source, name))):
            if 0xe000 <= start+offset <= 0xf8ff:
                entries.append((start+offset, glyphs[glyph+i]))
    assert entries and all(a[0]<b[0] for a,b in zip(entries,entries[1:]))
    data = bytearray()
    descriptors = ['    {0},']
    for cp, glyph in entries:
        count = (glyph['box_w']*glyph['box_h']*4+7)//8
        offset = glyph['bitmap_index']
        chunk = bitmap[offset:offset+count]
        assert len(chunk) == count
        glyph = dict(glyph, bitmap_index=len(data))
        descriptors.append('    {' + ', '.join(f'.{k} = {v}' for k,v in glyph.items()) + f'}}, /* U+{cp:04X} */')
        data.extend(chunk)
    prefix = f'symbols_{size}'
    first = entries[0][0]
    bitmap_lines = ['    '+', '.join(f'0x{x:02x}' for x in data[i:i+16])+',' for i in range(0,len(data),16)]
    offsets = ', '.join(f'0x{cp-first:04x}' for cp,_ in entries)
    metrics = {name: int(re.search(r'\.'+name+r'\s*=\s*(-?\d+)', source)[1])
               for name in ('line_height','base_line')}
    return f'''
static const uint8_t {prefix}_bitmap[] = {{
{chr(10).join(bitmap_lines)}
}};
static const lv_font_fmt_txt_glyph_dsc_t {prefix}_glyphs[] = {{
{chr(10).join(descriptors)}
}};
static const uint16_t {prefix}_unicode[] = {{{offsets}}};
static const lv_font_fmt_txt_cmap_t {prefix}_cmap[] = {{{{
    .range_start = {first}, .range_length = {entries[-1][0]-first+1}, .glyph_id_start = 1,
    .unicode_list = {prefix}_unicode, .list_length = {len(entries)},
    .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
}}}};
static const lv_font_fmt_txt_dsc_t {prefix}_data = {{
    .glyph_bitmap = {prefix}_bitmap, .glyph_dsc = {prefix}_glyphs,
    .cmaps = {prefix}_cmap, .cmap_num = 1, .bpp = 4
}};
static const lv_font_t {prefix}_font = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {metrics['line_height']}, .base_line = {metrics['base_line']},
    .subpx = LV_FONT_SUBPX_NONE,
#if LV_VERSION_CHECK(9, 3, 0)
    .static_bitmap = 1,
#endif
    .dsc = &{prefix}_data, .fallback = LV_FONT_DEFAULT
}};
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--lvgl-font-dir', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    output = '''/* Generated by tools/fonts/generate_ui_symbols.py; do not edit glyph data.
 * Source: LVGL's Font Awesome Free symbols, SIL OFL 1.1.
 * See fonts/symbols-LICENSE.txt. All font/bitmap data is read-only.
 */
#include "pxa/lvgl/pxa_lvgl_ui.h"
#include "lvgl.h"
'''
    for size in SIZES:
        output += extract(args.lvgl_font_dir/f'lv_font_montserrat_{size}.c', size)
    output += '''
const void *pxa_lvgl_ui_icon_font(uint32_t density_q16) {
    /* Graphics follow dp, independently of the user's text scale. Match the
     * closest pre-rasterized 18 dp symbol bank; no resize layer or font cache. */
    uint64_t target = ((uint64_t)(density_q16 ? density_q16 : 65536u) * 18u + 32768u) >> 16;
    static const struct { uint8_t size; const lv_font_t *font; } banks[] = {
'''
    output += ''.join(f'        {{{size}, &symbols_{size}_font}},\n' for size in SIZES)
    output += '''    };
    unsigned best = 0;
    uint64_t distance = target > banks[0].size ? target-banks[0].size : banks[0].size-target;
    for (unsigned i=1; i<sizeof(banks)/sizeof(banks[0]); ++i) {
        uint64_t delta = target > banks[i].size ? target-banks[i].size : banks[i].size-target;
        if (delta < distance) { best=i; distance=delta; }
    }
    return banks[best].font;
}
'''
    args.output.write_text(output)
    print(f'{args.output}: {len(output)} source bytes')


if __name__ == '__main__':
    main()
