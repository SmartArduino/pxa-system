#!/usr/bin/env python3
"""Generate the optional 12 px IME label font from the product's SC sans face.

Requires Pillow. Usage: generate_ime_labels.py FONT.ttf OUTPUT.h
The generated A8 bitmaps live in read-only code, with no runtime glyph cache.
"""
import hashlib
import pathlib
import sys
from PIL import Image, ImageDraw, ImageFont

source,output=map(pathlib.Path,sys.argv[1:])
font=ImageFont.truetype(str(source),12)
labels='·拼音中文九键全键标点分词完成空格返回符号正在准备词库请稍候英文密码系统盘下一页上一首页'
chars=sorted(set(labels),key=ord)
bitmap=bytearray();glyphs=['    {0}, /* missing glyph */']
for char in chars:
    left,top,right,bottom=font.getbbox(char,anchor='ls')
    image=Image.new('L',(right-left,bottom-top))
    ImageDraw.Draw(image).text((-left,-top),char,font=font,fill=255,anchor='ls')
    glyphs.append(f'    {{.bitmap_index={len(bitmap)},.adv_w={round(font.getlength(char)*16)},.box_w={right-left},.box_h={bottom-top},.ofs_x={left},.ofs_y={-bottom}}}, /* {char} */')
    bitmap.extend(image.tobytes())
first=ord(chars[0]);last=ord(chars[-1]);unicode=','.join(str(ord(c)-first) for c in chars)
lines=['/* Generated by tools/fonts/generate_ime_labels.py. Font data: OFL-1.1.',
       f' * PXA Sans SC Regular, source SHA256 {hashlib.sha256(source.read_bytes()).hexdigest()}.',
       ' * See fonts/NOTICE.md and fonts/OFL.txt. */','#pragma once',
       'static const uint8_t ime_label_bitmap[] = {']
lines.extend('    '+','.join(str(v) for v in bitmap[i:i+24])+',' for i in range(0,len(bitmap),24))
lines+=['};','static const lv_font_fmt_txt_glyph_dsc_t ime_label_glyphs[] = {',*glyphs,'};',
        f'static const uint16_t ime_label_unicode[] = {{{unicode}}};',
        'static const lv_font_fmt_txt_cmap_t ime_label_cmap[] = {',
        f'    {{.range_start={first},.range_length={last-first+1},.glyph_id_start=1,.unicode_list=ime_label_unicode,.list_length={len(chars)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},','};',
        'static const lv_font_fmt_txt_dsc_t ime_label_dsc = {',
        '    .glyph_bitmap=ime_label_bitmap,.glyph_dsc=ime_label_glyphs,.cmaps=ime_label_cmap,.cmap_num=1,.bpp=8,','};',
        'static const lv_font_t ime_label_12 = {',
        '    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
        '    .line_height=14,.base_line=2,.static_bitmap=1,.dsc=&ime_label_dsc,','};','']
output.write_text('\n'.join(lines))
print(f'{len(chars)} SC sans glyphs, {len(bitmap)} bytes A8 bitmap in ROM')
