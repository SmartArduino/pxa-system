#!/usr/bin/env python3
"""Generate/check release metadata; ABI versions keep their own authority.

VERSION is the only handwritten release number. The protocol registry and
explicit common Host feature baseline generate the store's profile metadata.
Run --check as a release gate, including both dependent repositories.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/package'))
from protocol_metadata import SERVICE_IDS, SERVICE_VERSIONS, SERVICE_FEATURES, read_spec


def outputs(workspace=None, backend=None):
    version = (ROOT / 'VERSION').read_text().strip()
    match = re.fullmatch(r'(\d+)\.(\d+)\.(\d+)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?', version)
    if not match:
        raise ValueError('VERSION must contain a semantic release version')
    major, minor, patch = match.groups()
    result = {ROOT / 'libpxa/include/pxa/version.h': f'''/* Generated by tools/release/metadata.py from VERSION. */
#ifndef PXA_VERSION_H
#define PXA_VERSION_H

#define PXA_VERSION_MAJOR {major}
#define PXA_VERSION_MINOR {minor}
#define PXA_VERSION_PATCH {patch}
#define PXA_VERSION_STRING "{version}"

#endif
'''}
    idf = ROOT / 'idf_component.yml'
    result[idf] = re.sub(r'^version:.*$', f'version: "{version}"', idf.read_text(), count=1, flags=re.M)
    if workspace:
        for name in ('pxadb', 'pxadb-gui'):
            path = workspace / 'tools' / name / 'pyproject.toml'
            result[path] = re.sub(r'^version =.*$', f'version = "{version}"', path.read_text(), count=1, flags=re.M)
    if backend:
        declared = json.loads((ROOT / 'config/host-baseline-features.json').read_text())
        services = []
        for name, service_id in sorted(SERVICE_IDS.items(), key=lambda entry: entry[1]):
            bits = 0
            for feature in declared.get(name, []):
                bits |= SERVICE_FEATURES[name][feature]
            service_major, service_minor = SERVICE_VERSIONS[service_id]
            services.append({'service_id': service_id, 'name': name, 'major': service_major,
                             'minor': service_minor, 'features': bits})
        core = read_spec('core')['abi']
        wamr = json.loads((ROOT / 'config/wamr.json').read_text())
        document = {'schema': 'pxa-host-baseline-1', 'release': version,
                    'core': [core['major'], core['minor']], 'engine_abi': wamr['engine_abi'], 'services': services}
        result[backend / 'app/pxa-capabilities.json'] = json.dumps(document, indent=2) + '\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--workspace', type=Path)
    parser.add_argument('--backend', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    mismatches = []
    for path, expected in outputs(args.workspace, args.backend).items():
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                mismatches.append(str(path))
        else:
            path.write_text(expected)
    if mismatches:
        parser.exit(1, 'Release metadata differs: ' + ', '.join(mismatches) + '\n')


if __name__ == '__main__':
    main()
