#!/usr/bin/env python3
"""Generate immutable builtin IME dictionaries; normal builds use checked-in data."""
import argparse,json,hashlib
from collections import defaultdict
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
DATA=Path(__file__).resolve().parent/'data'
OUT=ROOT/'libpxa/adapters/lvgl/dictionaries'

def generate():
    frequency={}
    for line in (DATA/'frequency.tsv').read_text(encoding='utf-8').splitlines():
        if line and not line.startswith('#'):
            py,chars=line.split('\t');frequency[py]={c:i for i,c in enumerate(chars)}
    traditional_readings={}
    for line in (DATA/'traditional-readings.tsv').read_text(encoding='utf-8').splitlines():
        if line and not line.startswith('#'):
            c,py=line.split('\t');traditional_readings[c]=py.split(',')
    tables={'simplified':defaultdict(dict),'traditional':defaultdict(dict)};standard={};counterparts=set()
    for c,readings in traditional_readings.items():
        for py in readings:tables['traditional'][py][c]=(100000,100000,ord(c))
    for line in (DATA/'tgh2013.tsv').read_text(encoding='utf-8').splitlines():
        if not line or line.startswith('#'):continue
        index,char,readings,traditional=line.split('\t');index=int(index)
        assert len(char)==1 and char not in standard and traditional
        standard[char]=index;counterparts.update(traditional)
        for py in readings.split(','):
            assert py.isascii() and py.isalpha() and len(py)<=6
            rank=(frequency.get(py,{}).get(char,100000),index,ord(char))
            for name,chars in (('simplified',char),('traditional',traditional)):
                for c in chars:
                    if name=='traditional' and py not in traditional_readings[c]:continue
                    old=tables[name][py].get(c)
                    tables[name][py][c]=min(old,rank) if old else rank
    assert len(standard)==8105 and set(standard.values())==set(range(1,8106))
    outputs={};report={'source_sha256':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(DATA.glob('*.tsv'))}}
    for name,table in tables.items():
        for alias,canonical in (('lve','lue'),('nve','nue')):
            if canonical in table:table[alias]=table[canonical].copy()
        rows=[];pool=[];offset=0;seen=set();readings=0
        for py,chars in sorted(table.items()):
            text=''.join(sorted(chars,key=chars.get));rows.append((py,offset));pool.append(text);offset+=len(text.encode('utf8'))+1;seen.update(text);readings+=len(text)
        assert offset<65536
        complete=defaultdict(int);keys='22233344455566677778889999'
        for py,_ in rows:complete[''.join(keys[ord(c)-97] for c in py)]+=1
        assert max(complete.values())<=32
        if name=='simplified':assert seen==set(standard)
        else:assert counterparts<=seen
        header=['/* Generated by tools/ime/generate_builtin.py; do not edit.', ' * Data: Unicode-3.0 AND Apache-2.0; see tools/ime/NOTICE.md. */']
        header.append(f'static const builtin_syllable_t builtin_{name}_rows[] = {{')
        header.extend(f'    {{"{py}",{len(py)},{off}}},' for py,off in rows);header.append('};')
        header.append(f'static const unsigned char builtin_{name}_characters[] = {{')
        encoded=b''.join(text.encode('utf8')+b'\0' for text in pool)+b'\0'
        header.extend('    '+','.join(f'0x{byte:02x}' for byte in encoded[i:i+16])+',' for i in range(0,len(encoded),16))
        header.append('};\n')
        outputs[OUT/(name+'.h')]='\n'.join(header)
        report[name]={'syllables':len(rows),'readings_including_input_aliases':readings,
            'unique_characters':len(seen),'pool_bytes':offset+1,'row_bytes':len(rows)*10,
            'static_bytes':offset+1+len(rows)*10,'max_t9_complete_spellings':max(complete.values())}
        if name=='simplified':
            report[name]['standard_levels']={str(limit):sum(c in seen for c,i in standard.items() if i<=limit)
                                             for limit in (3500,6500,8105)}
        else:
            report[name]['all_standard_character_counterparts_present']=counterparts<=seen
            report[name]['standard_source_characters']=len(standard)
    outputs[DATA/'coverage.json']=json.dumps(report,ensure_ascii=False,indent=2)+'\n'
    return outputs

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true')
    p.add_argument('--corpus',choices=('simplified','traditional','both'));p.add_argument('--corpus-output',type=Path)
    args=p.parse_args()
    if bool(args.corpus)!=bool(args.corpus_output):p.error('--corpus and --corpus-output must be supplied together')
    for path,text in generate().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8')!=text:raise SystemExit('Stale generated dictionary: '+str(path))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text,encoding='utf-8')
    if args.corpus:
        chars=set()
        if args.corpus in ('simplified','both'):
            chars.update(line.split('\t')[1] for line in (DATA/'tgh2013.tsv').read_text(encoding='utf-8').splitlines() if line and not line.startswith('#'))
        if args.corpus in ('traditional','both'):
            chars.update(line.split('\t')[0] for line in (DATA/'traditional-readings.tsv').read_text(encoding='utf-8').splitlines() if line and not line.startswith('#'))
        args.corpus_output.write_text(''.join(sorted(chars)),encoding='utf-8')
    print((DATA/'coverage.json').read_text(encoding='utf-8'))
if __name__=='__main__':main()
