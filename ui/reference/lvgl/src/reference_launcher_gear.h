/* The outline uses hundredths of a pixel in the original 32 px artwork. */
static bool launcher_gear_tooth_contains(int32_t along, int32_t across) {
    const int32_t dx = LV_MAX(0, LV_MAX(895 - along, along - 1385));
    const int32_t dy = LV_MAX(0, across - 215);
    return dx * dx + dy * dy <= 65 * 65;
}

static bool launcher_gear_contains(int32_t x, int32_t y) {
    const int32_t r2 = x * x + y * y;
    if (r2 < 505 * 505) return false;
    if (r2 <= 1000 * 1000) return true;
    return launcher_gear_tooth_contains(LV_MAX(x, y), LV_MIN(x, y)) ||
           launcher_gear_tooth_contains((x + y) * 7071 / 10000,
                                        LV_ABS(x - y) * 7071 / 10000);
}

static lv_draw_buf_t* launcher_gear_rasterize(uint32_t size) {
    lv_draw_buf_t* buffer = lv_draw_buf_create(size, size, LV_COLOR_FORMAT_A8,
                                               LV_STRIDE_AUTO);
    if (buffer == NULL) return NULL;
    const int32_t half = (int32_t)size / 2;
    const uint32_t stride = buffer->header.stride;
    /* Sample one octant and reflect it into the others. This preserves
     * symmetry and does the work once per launcher, outside the draw path. */
    for (int32_t y = 0; y < half; ++y) {
        for (int32_t x = y; x < half; ++x) {
            unsigned coverage = 0;
            for (int32_t sy = 0; sy < 4; ++sy) {
                const int32_t uy = (8 * y + 2 * sy + 1) * 400 / (int32_t)size;
                for (int32_t sx = 0; sx < 4; ++sx) {
                    const int32_t ux = (8 * x + 2 * sx + 1) * 400 / (int32_t)size;
                    coverage += launcher_gear_contains(ux, uy);
                }
            }
            const uint8_t alpha = (uint8_t)((coverage * 255 + 8) / 16);
            const int32_t columns[] = {half - 1 - x, half + x};
            const int32_t rows[] = {half - 1 - y, half + y};
            for (int32_t i = 0; i < 2; ++i) {
                for (int32_t j = 0; j < 2; ++j) {
                    buffer->data[rows[i] * stride + columns[j]] = alpha;
                    buffer->data[columns[j] * stride + rows[i]] = alpha;
                }
            }
        }
    }
    lv_draw_buf_flush_cache(buffer, NULL);
    return buffer;
}

