#!/usr/bin/env python3
"""Export the fixed PXA v1 identity; only pxa-logo-master.svg defines geometry.

Build tools: Python 3, Pillow, rsvg-convert. Nothing is linked into PXA.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
import hashlib
from io import BytesIO
from pathlib import Path
import shutil
import subprocess
import xml.etree.ElementTree as ET

from PIL import Image

ROOT = Path(__file__).resolve().parent
NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", NS)
DARK = {"ink": "#e5e7eb", "accent": "#b6f568", "facet": "#568144"}
LIGHT = {"ink": "#111827", "accent": "#568144", "facet": "#b6f568"}


def svg(master, layout, palette, background=None):
    views = {"stacked": "0 0 640 640", "mark": "128 32 392 392",
             "horizontal": "0 0 960 320", "boot": "0 0 1448 1086"}
    root = ET.Element(f"{{{NS}}}svg", {"viewBox": views[layout], "role": "img", "aria-label": "PXA"})
    if background:
        x, y, w, h = views[layout].split()
        ET.SubElement(root, f"{{{NS}}}rect", {"x": x, "y": y, "width": w, "height": h, "fill": background})
    for name in ["pxa-mark", "pxa-wordmark"]:
        if layout == "mark" and name == "pxa-wordmark":
            continue
        node = deepcopy(master.find(f".//*[@id='{name}']"))
        for item in node.iter():
            tone = item.attrib.pop("data-tone", None)
            if tone:
                item.set("fill", palette[tone])
        parent = root
        if layout in ["horizontal", "boot"]:
            transform = "translate(410 212)" if layout == "boot" else (
                "translate(-88 -10) scale(.75)" if name == "pxa-mark" else "translate(301 -346)")
            parent = ET.SubElement(root, f"{{{NS}}}g", {"transform": transform})
        parent.append(node)
    return ET.tostring(root, encoding="utf-8", xml_declaration=True) + b"\n"


def render(data, width, height):
    return subprocess.run(["rsvg-convert", "--width", str(width), "--height", str(height)],
                          input=data, check=True, stdout=subprocess.PIPE).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "dist")
    parser.add_argument("--firmware-header", type=Path)
    parser.add_argument("--website-root", type=Path, help="pxa_app_store_backend checkout; copies assets only")
    args = parser.parse_args()
    out = args.output
    out.mkdir(parents=True, exist_ok=True)
    master = ET.fromstring((ROOT / "pxa-logo-master.svg").read_bytes())
    shutil.copy2(ROOT.parent / "LICENSE", out / "LICENSE")
    shutil.copy2(ROOT / "pxa-logo-master.svg", out / "pxa-logo-master.svg")
    for layout in ["stacked", "horizontal", "mark"]:
        for name, colors in [("dark", DARK), ("light", LIGHT),
                             ("mono-dark", dict.fromkeys(DARK, DARK["ink"])),
                             ("mono-light", dict.fromkeys(DARK, LIGHT["ink"]))]:
            (out / f"pxa-{layout}-{name}.svg").write_bytes(svg(master, layout, colors))
    icon = svg(master, "mark", DARK, "#111827")
    (out / "favicon.svg").write_bytes(icon)
    light_icon = svg(master, "mark", LIGHT, "#f8faf7")
    (out / "favicon-light.svg").write_bytes(light_icon)
    (out / "pxa-icon-light-32.png").write_bytes(render(light_icon, 32, 32))
    for size in [16, 32, 180, 192, 512]:
        (out / f"pxa-icon-{size}.png").write_bytes(render(icon, size, size))
    boot = svg(master, "boot", DARK, "#111827")
    (out / "pxa-boot.svg").write_bytes(boot)
    (out / "pxa-boot-320x240.png").write_bytes(render(boot, 320, 240))
    (out / "pxa-boot-preview.png").write_bytes(render(boot, 960, 720))
    if args.firmware_header:
        # RGB565 in native uint16_t storage. No SVG/PNG decoder or filesystem at boot.
        pixels = Image.open(BytesIO((out / "pxa-boot-320x240.png").read_bytes())).convert("RGB")
        values = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in pixels.getdata()]
        digest = hashlib.sha256((ROOT / "pxa-logo-master.svg").read_bytes()).hexdigest()
        lines = ["// Generated by deps/pxa-system/branding/export.py. Do not edit.",
                 "// SPDX-License-Identifier: MIT", f"// Master SVG SHA256: {digest}",
                 "#pragma once", "#include <cstdint>", "namespace pxa_brand {",
                 "inline constexpr unsigned kWidth = 320, kHeight = 240;",
                 "alignas(64) inline constexpr uint16_t kBootRgb565[] = {"]
        lines += ["    " + ",".join(f"0x{v:04x}" for v in values[i:i+16]) + "," for i in range(0, len(values), 16)]
        lines += ["};", "} // namespace pxa_brand", ""]
        args.firmware_header.parent.mkdir(parents=True, exist_ok=True)
        args.firmware_header.write_text("\n".join(lines))
    if args.website_root:
        for target in [args.website_root / "pxa-website/assets/brand", args.website_root / "app/static/brand"]:
            target.mkdir(parents=True, exist_ok=True)
            for file in out.iterdir():
                shutil.copy2(file, target / file.name)
        for target in [args.website_root / "pxa-website/assets/favicon.svg", args.website_root / "app/static/favicon.svg"]:
            shutil.copy2(out / "favicon.svg", target)
    print(f"PXA v1 assets: {out}")


if __name__ == "__main__":
    main()
